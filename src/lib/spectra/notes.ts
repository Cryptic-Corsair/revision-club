export function getNotes(docId: string): NotesDoc | undefined {
  return NOTES_DOCS.find((d) => d.id === docId);
}

export function getNotesForTopic(unitCode: string, topicId: string): NotesDoc | undefined {
  return NOTES_DOCS.find((d) => d.unitCode === unitCode && d.topicId === topicId);
}

/* dev guard — the shell routes on notes-meta.ts, so the two lists
   must agree or notes open into nothing. Loud, not silent. */
if (process.env.NODE_ENV !== "production") {
  if (NOTES_META.length !== NOTES_DOCS.length) {
    console.error(
      "[notes] notes-meta.ts and NOTES_DOCS disagree on count — re-run scripts/gen-notes-meta.ts",
    );
  }
  for (const d of NOTES_DOCS) {
    const m = NOTES_META.find((x) => x.id === d.id);
    if (!m) {
      console.error(
        `[notes] doc ${d.id} has no card in notes-meta.ts — re-run scripts/gen-notes-meta.ts`,
      );
    } else if (m.title !== d.title || m.kicker !== d.kicker || m.source !== d.source) {
      console.error(
        `[notes] notes-meta.ts card for ${d.id} is stale — re-run scripts/gen-notes-meta.ts`,
      );
    }
  }
}
