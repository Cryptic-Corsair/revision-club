export function getNotesMeta(docId: string): NotesMeta | undefined {
  return NOTES_META.find((m) => m.id === docId);
}

export function getNotesMetaForTopic(
  unitCode: string,
  topicId: string,
): NotesMeta | undefined {
  return NOTES_META.find((m) => m.unitCode === unitCode && m.topicId === topicId);
}
